def keep_dark_shadow_off(cut, y0=0.66, lum_max=0.20, sat_max=0.12):
    h = cut.shape[0]
    lum = cut[..., :3].mean(-1)
    sat = cut[..., :3].max(-1) - cut[..., :3].min(-1)
    low = np.zeros(cut.shape[:2], bool)
    low[int(y0 * h):] = True
    cut[..., 3] = np.where(low & (lum < lum_max) & (sat < sat_max), 0.0, cut[..., 3])
    return cut


